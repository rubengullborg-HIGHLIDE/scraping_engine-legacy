-- Weekday source catalogue: one row per style/colour, Aarhus only.
-- Initial import retains only positive Aarhus observations. Refresh may later
-- set availability false; lack of a new catalogue row never deletes old rows.
create table public.weekday_products (
    id bigint generated by default as identity primary key,
    source_parent_id text not null check (source_parent_id ~ '^[0-9]{7}$'),
    source_color_id text not null check (source_color_id ~ '^[0-9]{10}$'),
    canonical_url text not null,
    name text not null,
    brand text not null check (brand in ('Weekday', 'Cheap Monday')),
    color text,
    category_path text[] not null default '{}',
    description_html text,
    images text[] not null default '{}',
    material jsonb not null default '{}',
    fit jsonb not null default '{}',
    current_price numeric(12,2) not null check (current_price >= 0),
    list_price numeric(12,2) check (list_price >= 0),
    currency text not null default 'DKK' check (currency = 'DKK'),
    local_inventory jsonb not null check (jsonb_typeof(local_inventory -> 'stores') = 'object'),
    local_total_stock integer check (local_total_stock >= 0),
    local_available boolean,
    aarhus_total_stock integer check (aarhus_total_stock >= 0),
    aarhus_available boolean,
    inventory_complete boolean not null,
    inventory_warnings text[] not null default '{}',
    price_observed_at timestamptz not null,
    inventory_observed_at timestamptz not null,
    raw jsonb not null default '{}',
    first_seen_at timestamptz not null default now(),
    scraped_at timestamptz not null,
    updated_at timestamptz not null default now(),
    unique (source_parent_id, source_color_id),
    check (left(source_color_id, 7) = source_parent_id),
    check (local_inventory ? 'stores'),
    check ((local_inventory -> 'stores') ? 'weekday-aarhus'),
    check (((local_inventory -> 'stores') - 'weekday-aarhus') = '{}'::jsonb),
    check (inventory_complete or aarhus_total_stock is null)
);

comment on column public.weekday_products.local_total_stock is
    'Sum of explicit Aarhus quantities; only a lower bound if inventory_complete is false.';
comment on column public.weekday_products.aarhus_total_stock is
    'Exact Aarhus total, null for capped/unmapped or otherwise incomplete observations.';
comment on column public.weekday_products.raw is
    'Full-import source metadata, size SKU map and physical inventory references; not dynamic history.';

create index weekday_products_aarhus_available_idx
    on public.weekday_products (aarhus_available, inventory_observed_at);

-- Replaying an interrupted import must not replace newer observations. A partial
-- stock response cannot overwrite existing inventory. The importer additionally
-- excludes partial stock and missing-image products before any database write.
create function public.guard_weekday_product_observations()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
    new.first_seen_at := old.first_seen_at;
    if new.price_observed_at <= old.price_observed_at then
        new.current_price := old.current_price;
        new.list_price := old.list_price;
        new.currency := old.currency;
        new.price_observed_at := old.price_observed_at;
    end if;
    if not new.inventory_complete or new.inventory_observed_at <= old.inventory_observed_at then
        new.local_inventory := old.local_inventory;
        new.local_total_stock := old.local_total_stock;
        new.local_available := old.local_available;
        new.aarhus_total_stock := old.aarhus_total_stock;
        new.aarhus_available := old.aarhus_available;
        new.inventory_complete := old.inventory_complete;
        new.inventory_warnings := old.inventory_warnings;
        new.inventory_observed_at := old.inventory_observed_at;
    end if;
    new.scraped_at := greatest(old.scraped_at, new.scraped_at);
    new.updated_at := now();
    return new;
end;
$$;

create trigger guard_weekday_product_observations
before update on public.weekday_products
for each row execute function public.guard_weekday_product_observations();

alter table public.weekday_products enable row level security;
revoke all on public.weekday_products from public, anon, authenticated;
grant select, insert, update on public.weekday_products to service_role;
revoke all on sequence public.weekday_products_id_seq from public, anon, authenticated;
grant usage, select on sequence public.weekday_products_id_seq to service_role;
revoke all on function public.guard_weekday_product_observations() from public, anon, authenticated;
grant execute on function public.guard_weekday_product_observations() to service_role;
